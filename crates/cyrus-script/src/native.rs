impl Native {
    /// The function's installed spelling.
    pub const fn name(self) -> &'static str {
        NAMES[self as usize]
    }

    /// The native an installed name declares; SOUP names are case-insensitive.
    pub fn from_name(name: &str) -> Option<Self> {
        NAMES
            .iter()
            .position(|known| known.eq_ignore_ascii_case(name))
            .map(|index| ALL[index])
    }
}

impl fmt::Display for Native {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.name())
    }
}

/// Programs keep the installed spelling, so decoded and cached programs read the same.
impl Serialize for Native {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.name())
    }
}

impl<'de> Deserialize<'de> for Native {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let name = <std::borrow::Cow<'de, str>>::deserialize(deserializer)?;
        Self::from_name(&name).ok_or_else(|| {
            serde::de::Error::custom(format!("function {name} absent from SOUP386.DEF"))
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn variants_follow_the_installed_order_and_spelling() {
        assert_eq!(Native::NullFunction as usize, 0);
        assert_eq!(Native::SRotate as usize, 1);
        assert_eq!(Native::Activate.name(), "ACTIVATE");
        assert_eq!(Native::from_name("activate"), Some(Native::Activate));
        assert_eq!(Native::from_name("NoSuchNative"), None);
        for (index, native) in ALL.into_iter().enumerate() {
            assert_eq!(native as usize, index);
            assert_eq!(Native::from_name(native.name()), Some(native));
        }
    }

    #[test]
    fn serializes_as_the_installed_name() {
        let json = serde_json::to_string(&Native::PlayerDistance).unwrap();
        assert_eq!(json, "\"PlayerDistance\"");
        assert_eq!(
            serde_json::from_str::<Native>(&json).unwrap(),
            Native::PlayerDistance
        );
        assert!(serde_json::from_str::<Native>("\"Bogus\"").is_err());
    }
}
