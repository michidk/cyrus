//! SOUP native functions: the `[functions]` list of the installed `SOUP386.DEF`.
//!
//! Variants are the DEF names with a leading capital, in DEF order after preservation's synthetic
//! `NullFunction` at index zero, so a declared variant's position is the call's `function_id`.
//! The last variants are engine natives the installed DEF does not declare; preservation
//! `docs/engine/SOUP.md` and `docs/engine/sound.md` document their handlers. Installed names
//! become [`Native`] when a program is decoded; Rust code never matches function names as strings.
