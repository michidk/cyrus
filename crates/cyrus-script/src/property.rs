impl Property {
    /// The property's installed spelling.
    pub const fn name(self) -> &'static str {
        NAMES[self as usize]
    }

    /// The property an installed name declares; SOUP names are case-insensitive.
    pub fn from_name(name: &str) -> Option<Self> {
        NAMES
            .iter()
            .position(|known| known.eq_ignore_ascii_case(name))
            .map(|index| ALL[index])
    }
}

impl fmt::Display for Property {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.name())
    }
}

/// Definitions keep the installed spelling, so decoded and cached definitions read the same.
impl Serialize for Property {
    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        serializer.serialize_str(self.name())
    }
}

impl<'de> Deserialize<'de> for Property {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        let name = <std::borrow::Cow<'de, str>>::deserialize(deserializer)?;
        Self::from_name(&name).ok_or_else(|| {
            serde::de::Error::custom(format!("reference {name} absent from SOUP386.DEF"))
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn variants_follow_the_installed_order_and_spelling() {
        assert_eq!(Property::Address as usize, 0);
        assert_eq!(Property::Grip0.name(), "grip[0]");
        assert_eq!(
            Property::from_name("ANIM.CURRENT"),
            Some(Property::AnimCurrent)
        );
        assert_eq!(Property::from_name("no_such_ref"), None);
        for (index, property) in ALL.into_iter().enumerate() {
            assert_eq!(property as usize, index);
            assert_eq!(Property::from_name(property.name()), Some(property));
        }
    }

    #[test]
    fn serializes_as_the_installed_name() {
        let json = serde_json::to_string(&Property::TaskVariable2_0).unwrap();
        assert_eq!(json, "\"task_variable2[0]\"");
        assert_eq!(
            serde_json::from_str::<Property>(&json).unwrap(),
            Property::TaskVariable2_0
        );
        assert!(serde_json::from_str::<Property>("\"bogus\"").is_err());
    }
}
