//! `lookObj` reproduces the original handler step by step.
//!
//! Each case gives synthetic receiver attributes, pose and a duration, and the camera state the
//! original left after every invocation until the task completed: selection, scripted words,
//! private counter, published angles, the bound record and record zero's flags. The cases come
//! from running the original routine over a controlled receiver and a camera that has published a
//! fixed pose.
use cyrus_game::script::{ScriptActorId, camera::*};

#[derive(Debug, PartialEq)]
struct Record {
    position_offset: [i32; 3],
    angle_offset: [i32; 3],
    request: [i32; 3],
    target_offset: [i32; 3],
    distance: i32,
    flags: u8,
}

struct Step {
    running: bool,
    selected: usize,
    index: usize,
    active: u16,
    nesting: u32,
    counter: u32,
    marks: (bool, bool, bool),
    pose_angles: [i32; 3],
    scratch: Record,
    record_zero_flags: u8,
}

struct Case {
    name: &'static str,
    camera_move: u8,
    attributes: [u8; 6],
    position: [i32; 3],
    angles: [u16; 3],
    duration: i32,
    steps: &'static [Step],
}

