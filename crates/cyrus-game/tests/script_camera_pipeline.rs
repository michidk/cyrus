//! The camera pose stage reproduces the original routine, executed over controlled inputs.
//!
//! Each case lists synthetic record, player and published-pose values and the pose, history,
//! transition word and logical actor position the original stage produced. The scene has no
//! obstacle models and no terrain; collision correction is covered by its own contracts.
use anyhow::Result;
use cyrus_game::script::{ScriptActorId, camera::*};

struct NoGeometry;
impl CameraGeometry for NoGeometry {
    fn segment(
        &mut self,
        _: [i32; 3],
        _: [i32; 3],
        _: ScriptActorId,
    ) -> Result<Vec<cyrus_collision::collision_mesh::IntegerSegmentContact>> {
        Ok(vec![])
    }
    fn contacts(&mut self, _: [i32; 3], _: ScriptActorId) -> Result<Vec<[i32; 3]>> {
        Ok(vec![])
    }
    fn terrain_height(&mut self, _: [i32; 2]) -> Result<f32> {
        anyhow::bail!("terrain is disabled in these cases")
    }
}

