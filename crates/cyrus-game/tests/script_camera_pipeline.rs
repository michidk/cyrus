#[test]
fn pose_stage_reproduces_the_original_without_obstacles() {
    let actor = |index| ScriptActorId {
        generation: 1,
        index,
    };
    for case in CASES {
        let settings = CameraSettings::default();
        let mut state = CameraState::new(&settings, actor(2), actor(3), 0).unwrap();
        let slot = CameraSlot::new(case.slot).unwrap();
        state.selected = slot;
        state.index = slot;
        state.transition = case.transition;
        state.current = CameraPose {
            position: case.published,
            angles: case.published_angles,
        };
        state.previous = CameraPose {
            position: case.previous,
            angles: case.previous_angles,
        };
        let record = &mut state.records[slot.index()];
        record.position_offset = case.offset_pos;
        record.angle_offset = case.offset_angle;
        record.request = case.request;
        record.target_offset = case.target_offset;
        record.distance = case.distance;
        record.minimum_distance = case.min_distance;
        record.maximum_movement = case.max_vel;
        record.flags = case.flags;
        let hits = CameraHitSelection {
            minimum_position: [0; 3],
            maximum_position: [0; 3],
            minimum_normal: [0; 3],
            maximum_normal: [0; 3],
        };
        let update = state
            .prepare_pose(
                &hits,
                &CameraUpdateInputs {
                    bound_position: case.player_position,
                    bound_angles: case.player_angles,
                    movement: MovementLimits {
                        budget_increment: case.max_acc,
                        vertical: -case.max_y_vel,
                        frame_scale: case.frame_scale,
                        selected_player_special_state: false,
                    },
                    body_radius: 10.0,
                    body_clearance: 5.0,
                    collision_inhibited: false,
                    terrain_enabled: false,
                },
                &mut NoGeometry,
            )
            .unwrap_or_else(|error| panic!("{}: {error:#}", case.name));
        let published = update.state.current;
        assert_eq!(
            (published.position, published.angles),
            (case.pose, case.pose_angles),
            "{}: pose",
            case.name
        );
        assert_eq!(
            (update.state.previous.position, update.state.previous.angles),
            (case.history, case.history_angles),
            "{}: history",
            case.name
        );
        assert_eq!(
            update.state.transition, case.after_transition,
            "{}: transition",
            case.name
        );
        for (_, position) in update.actor_positions {
            assert_eq!(position, case.pose, "{}: actor position", case.name);
        }
    }
}
