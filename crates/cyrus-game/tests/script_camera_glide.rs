#[test]
fn render_step_reproduces_the_original_glide_and_cut() {
    for (number, case) in CASES.iter().enumerate() {
        let mut state =
            CameraState::new(&CameraSettings::default(), actor(2), actor(3), 0).unwrap();
        state.select(case.index as u8).unwrap();
        assert_eq!(state.index.index(), case.index);
        let flags = &mut state.records[state.selected.index()].flags;
        *flags = 0x40 | if case.selected_flag_20 { 0x20 } else { 0 };
        state.scripted_active = case.scripted_active;
        state.current = CameraPose {
            position: case.published,
            angles: case.published_angles,
        };
        state.render = RenderPose {
            position: case.render_position,
            angles: case.render_angles,
        };
        let [snap, hold, forced_glide] = case.marks;
        state.marks = CameraMarks {
            snap,
            hold,
            forced_glide,
        };
        state
            .present(
                &GlideSettings {
                    position: case.glide_position,
                    angles: case.glide_angles,
                },
                &GlidePlayer {
                    holding_weapon: case.holding_weapon,
                    rope_attached: case.rope_attached,
                },
                case.ready,
                &mut |_| Ok(()),
            )
            .unwrap();
        assert_eq!(
            state.render.position.map(f32::to_bits),
            case.out_position,
            "case {number}: render position"
        );
        assert_eq!(
            state.current.angles, case.published_angles,
            "case {number}: published angles"
        );
        assert_eq!(
            [state.marks.snap, state.marks.hold, state.marks.forced_glide],
            case.out_marks,
            "case {number}: marks"
        );
        assert_eq!(
            state.render.angles, case.out_render_angles,
            "case {number}: retained render angles"
        );
    }
}
