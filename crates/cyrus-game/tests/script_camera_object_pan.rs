//! The object pans (`showObjPan`, `showObjPanLoc`) reproduce the original handlers step by step.
//!
//! Each case gives synthetic receiver attributes, pose and task arguments, and the camera state the
//! original left after every invocation until the task completed: selection, scripted words, private
//! counter, the bound record and record zero's flags. The cases come from running the original
//! routines over a controlled receiver and a camera that has published a fixed pose.
use cyrus_game::script::{ScriptActorId, camera::*};

#[derive(Debug, PartialEq)]
struct Record {
    position_offset: [i32; 3],
    angle_offset: [i32; 3],
    request: [i32; 3],
    target_offset: [i32; 3],
    distance: i32,
    flags: u8,
}

struct Step {
    running: bool,
    selected: usize,
    index: usize,
    active: u16,
    nesting: u32,
    counter: u32,
    scratch: Record,
    record_zero_flags: u8,
}

