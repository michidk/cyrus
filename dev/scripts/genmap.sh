#!/usr/bin/env bash
# Writes docs/MAP.md, the crate and module map, from the tracked sources: each
# crate's and each module's first `//!` line. Hand-written maps go stale; this
# one is regenerated at every land and `just gates` fails when it is.
#   genmap.sh          write docs/MAP.md
#   genmap.sh --check  exit 1 when docs/MAP.md differs from the sources
set -euo pipefail
cd "$(dirname "$0")/../.."
# Byte order, so the map does not depend on the caller's locale.
export LC_ALL=C

first_doc() {
    local line
    line=$(grep -m1 '^//!' "$1" 2>/dev/null || true)
    line=${line#//! }
    echo "${line:-(undocumented)}"
}

generate() {
    cat <<'HEADER'
# MAP — crates and modules

Generated by `dev/scripts/genmap.sh` from the first `//!` line of every tracked
source file. Do not edit: `just gates` fails when this file is stale. Document a
module where it is defined and regenerate.
HEADER
    for manifest in $(git ls-files -- 'crates/*/Cargo.toml' | sort); do
        local dir crate root
        dir=$(dirname "$manifest")
        crate=$(basename "$dir")
        root=$dir/src/lib.rs
        [ -f "$root" ] || root=$dir/src/main.rs
        echo
        echo "## \`$crate\` — $(first_doc "$root")"
        local files
        files=$(git ls-files -- "$dir/src/*.rs" "$dir/src/**/*.rs" | grep -vx "$root" | sort || true)
        [ -n "$files" ] && echo
        for file in $files; do
            echo "- \`${file#"$dir"/}\` — $(first_doc "$file")"
        done
    done
}

if [ "${1:-}" = --check ]; then
    diff -u docs/MAP.md <(generate) >/dev/null \
        || { echo "genmap: docs/MAP.md is stale; run just genmap" >&2; exit 1; }
    echo "genmap: current"
else
    generate > docs/MAP.md
    echo "wrote docs/MAP.md"
fi
